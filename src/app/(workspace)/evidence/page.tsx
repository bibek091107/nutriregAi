"use client";

import Link from "next/link";
import { useMemo, useState } from "react";
import { Icon } from "@/components/ui/Icon";
import { Badge, Button } from "@/components/ui/controls";
import { EmptyState, ErrorState, LoadingState } from "@/components/ui/states";
import { useWorkspace } from "@/components/shell/AppShell";
import { useResource } from "@/lib/hooks/useResource";
import { getEvidence, getReviewQueue } from "@/lib/api";
import { severityStyle } from "@/lib/presentation";
import { formatDate, humanize } from "@/lib/format";
import type { Evidence, EvidenceStatus, FindingSeverity, ReviewTask } from "@/lib/api/types";

const EVIDENCE_STATUS: Record<EvidenceStatus, { tone: "success" | "warning" | "muted" | "danger"; icon: string }> = {
  RELEVANT: { tone: "success", icon: "verified" },
  PARTIALLY_RELEVANT: { tone: "warning", icon: "rule" },
  PENDING: { tone: "muted", icon: "hourglass_empty" },
  NOT_RELEVANT: { tone: "danger", icon: "link_off" },
};

const SEVERITY_TABS: { value: "ALL" | FindingSeverity; label: string }[] = [
  { value: "ALL", label: "All" },
  { value: "HIGH", label: "High" },
  { value: "MEDIUM", label: "Med" },
  { value: "LOW", label: "Low" },
];

/**
 * Three-column Evidence Viewer (findings / document canvas / analysis panel).
 * Nothing is fabricated: citations, sections, pages and excerpts are rendered
 * only when the backend RAG system returns them.
 */
export default function EvidencePage() {
  const { products, reloadProducts } = useWorkspace();

  const findings = useResource<ReviewTask[]>((signal) => getReviewQueue(signal), []);
  const evidence = useResource<Evidence[]>((signal) => getEvidence(signal), []);

  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [severity, setSeverity] = useState<"ALL" | FindingSeverity>("ALL");
  const [search, setSearch] = useState("");
  const [activeEvidenceId, setActiveEvidenceId] = useState<string | null>(null);

  const allFindings = useMemo(() => findings.data ?? [], [findings.data]);
  const allEvidence = useMemo(() => evidence.data ?? [], [evidence.data]);

  const severityCounts = useMemo(() => {
    const base: Record<string, number> = { ALL: allFindings.length };
    for (const finding of allFindings) base[finding.severity] = (base[finding.severity] ?? 0) + 1;
    return base;
  }, [allFindings]);

  const visibleFindings = useMemo(() => {
    const term = search.trim().toLowerCase();
    return allFindings.filter((finding) => {
      if (severity !== "ALL" && finding.severity !== severity) return false;
      if (!term) return true;
      return finding.title.toLowerCase().includes(term) || finding.id.toLowerCase().includes(term);
    });
  }, [allFindings, severity, search]);

  const selected = useMemo(
    () => visibleFindings.find((finding) => finding.id === selectedId) ?? visibleFindings[0] ?? null,
    [visibleFindings, selectedId],
  );

  const selectedEvidence = useMemo(
    () => allEvidence.filter((item) => item.findingId === selected?.id),
    [allEvidence, selected],
  );

  const activeEvidence = useMemo(
    () =>
      selectedEvidence.find((item) => item.id === activeEvidenceId) ??
      selectedEvidence[0] ??
      null,
    [selectedEvidence, activeEvidenceId],
  );

  const activeProduct = products.find((product) => product.id === selected?.productId) ?? null;
  const loading = findings.status === "loading" || evidence.status === "loading";
  const errored = findings.status === "error" || evidence.status === "error";
  const errorMessage = findings.status === "error" ? findings.error.userMessage : evidence.status === "error" ? evidence.error.userMessage : "";

  const refresh = () => {
    findings.refetch();
    evidence.refetch();
    reloadProducts();
  };

  return (
    <div className="flex flex-col w-full">
      <header className="flex flex-col gap-space-sm mb-space-md">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-space-md">
          <div>
            <div className="flex items-center gap-space-xs">
              <span className="material-symbols-outlined text-secondary text-[24px]">policy</span>
              <h1 className="font-headline-lg text-headline-lg text-on-surface font-semibold tracking-tight">
                Evidence Viewer
              </h1>
            </div>
            <p className="font-body-sm text-body-sm text-on-surface-variant mt-0.5">
              Verify the regulatory sources and statutory gazettes supporting AI-generated compliance
              findings.
            </p>
          </div>
          <div className="flex items-center gap-space-sm">
            <Button variant="outline" icon="download" disabled title="Export is generated by the backend report endpoint">
              Export Evidence Pack
            </Button>
            <Link href={activeProduct ? `/products/${activeProduct.id}` : "/products"}>
              <Button variant="outline" icon="arrow_back">
                Back to Analysis
              </Button>
            </Link>
          </div>
        </div>

        <div className="bg-surface-container-lowest rounded-xl p-space-sm shadow-sm flex flex-wrap items-center justify-between gap-y-space-xs gap-x-space-md">
          <div className="flex flex-wrap items-center gap-x-space-md gap-y-1">
            <div className="flex items-center gap-1.5">
              <span className="font-label-caps text-label-caps text-on-surface-variant uppercase tracking-wider">
                Product:
              </span>
              <span className="font-body-sm text-body-sm font-semibold text-on-surface flex items-center gap-1">
                {activeProduct ? (
                  <>
                    <span className="w-1.5 h-1.5 rounded-full bg-secondary" />
                    {activeProduct.name}
                    {activeProduct.sku ? (
                      <span className="font-data-mono text-data-mono text-on-surface-variant">
                        ({activeProduct.sku})
                      </span>
                    ) : null}
                  </>
                ) : (
                  <span className="text-on-surface-variant font-normal">No product selected</span>
                )}
              </span>
            </div>
            {selected ? (
              <>
                <span className="text-surface-dim hidden sm:inline">•</span>
                <div className="flex items-center gap-1.5">
                  <span className="font-label-caps text-label-caps text-on-surface-variant uppercase tracking-wider">
                    Finding:
                  </span>
                  <span className="font-body-sm text-body-sm font-medium text-on-surface font-data-mono text-[12px]">
                    {selected.id}
                  </span>
                </div>
              </>
            ) : null}
            {selected ? (
              <>
                <span className="text-surface-dim hidden sm:inline">•</span>
                <div className="flex items-center gap-1.5">
                  <span className="font-label-caps text-label-caps text-on-surface-variant uppercase tracking-wider">
                    Active Status:
                  </span>
                  <Badge tone="active" dot dotClassName="bg-secondary">
                    {humanize(selected.status)}
                  </Badge>
                </div>
              </>
            ) : null}
          </div>
          <div className="flex items-center gap-space-sm font-data-mono text-[11px] text-on-surface-variant">
            <span className="flex items-center gap-1 text-secondary font-medium">
              <Icon className="text-[14px]">link</Icon>
              {selectedEvidence.length} Sources Linked
            </span>
            {selected?.requestedAt ? (
              <>
                <span className="text-surface-dim">•</span>
                <span>Requested: {formatDate(selected.requestedAt)}</span>
              </>
            ) : null}
          </div>
        </div>
      </header>

      {loading ? (
        <LoadingState label="Loading regulatory evidence..." rows={6} />
      ) : errored ? (
        <ErrorState title="Unable to retrieve evidence" message={errorMessage} onRetry={refresh} />
      ) : allEvidence.length === 0 && allFindings.length === 0 ? (
        <EmptyState
          icon="policy"
          title="No regulatory evidence available"
          description="Run a regulatory analysis so the RAG system can retrieve statutory sources for each finding."
          action={
            <Link href="/products">
              <Button variant="primary" icon="inventory_2">
                Go to products
              </Button>
            </Link>
          }
        />
      ) : (
        <div className="grid grid-cols-1 xl:grid-cols-12 gap-space-md items-start">
          {/* LEFT: findings */}
          <div className="xl:col-span-3 flex flex-col gap-space-sm bg-surface-container-lowest rounded-xl p-space-sm shadow-sm">
            <div className="flex items-center justify-between pb-space-xs">
              <div className="flex items-center gap-1.5">
                <span className="font-headline-sm text-headline-sm text-on-surface">Findings</span>
                <span className="font-data-mono text-data-mono px-1.5 py-0.2 bg-surface-container-low text-on-surface-variant rounded">
                  {allFindings.length}
                </span>
              </div>
            </div>

            <div className="relative w-full">
              <label htmlFor="evidence-search" className="sr-only">
                Search findings
              </label>
              <Icon className="absolute left-2.5 top-1/2 -translate-y-1/2 text-on-surface-variant text-[16px]">
                search
              </Icon>
              <input
                id="evidence-search"
                value={search}
                onChange={(event) => setSearch(event.target.value)}
                className="w-full h-8 pl-8 pr-2.5 text-body-sm font-body-sm rounded bg-surface border-0 focus:outline-none focus:ring-1 focus:ring-secondary text-on-surface placeholder:text-on-surface-variant/60"
                placeholder="Search findings, CAS, INS..."
              />
            </div>

            <div className="grid grid-cols-4 gap-1 p-0.5 bg-surface-container-low rounded">
              {SEVERITY_TABS.map((tab) => (
                <button
                  key={tab.value}
                  type="button"
                  onClick={() => setSeverity(tab.value)}
                  aria-pressed={severity === tab.value}
                  className={`py-1 text-center font-label-sm text-label-sm rounded transition-colors ${
                    severity === tab.value
                      ? "font-semibold bg-surface-container-lowest text-on-surface shadow-xs"
                      : "text-on-surface-variant hover:text-on-surface"
                  }`}
                >
                  {tab.label} ({severityCounts[tab.value] ?? 0})
                </button>
              ))}
            </div>

            <div className="flex flex-col gap-space-xs mt-1">
              {visibleFindings.length === 0 ? (
                <EmptyState
                  compact
                  icon="filter_alt_off"
                  title="No matching findings"
                  description="No findings match the current filter."
                />
              ) : (
                visibleFindings.map((finding) => {
                  const isActive = selected?.id === finding.id;
                  const evidenceCount = allEvidence.filter(
                    (item) => item.findingId === finding.id,
                  ).length;
                  return (
                    <div
                      key={finding.id}
                      role="button"
                      tabIndex={0}
                      onClick={() => {
                        setSelectedId(finding.id);
                        setActiveEvidenceId(null);
                      }}
                      onKeyDown={(event) => {
                        if (event.key === "Enter" || event.key === " ") {
                          event.preventDefault();
                          setSelectedId(finding.id);
                          setActiveEvidenceId(null);
                        }
                      }}
                      className={`relative p-space-sm rounded text-on-surface flex flex-col gap-1.5 cursor-pointer transition-all ${
                        isActive
                          ? "bg-surface-container shadow-xs"
                          : "bg-surface-container-low/70 hover:bg-surface-container-low"
                      }`}
                    >
                      <div className="flex items-center justify-between">
                        <span
                          className={`inline-flex items-center px-1.5 py-0.5 rounded font-label-caps text-[10px] font-bold tracking-wider uppercase ${
                            finding.severity === "HIGH"
                              ? "bg-error text-on-error"
                              : finding.severity === "MEDIUM"
                                ? "bg-surface-container-highest text-on-surface"
                                : "bg-surface-container-highest text-on-surface-variant"
                          }`}
                        >
                          {finding.severity === "LOW"
                            ? "Low Advisory"
                            : `${humanize(finding.severity)} Risk`}
                        </span>
                        {evidenceCount > 0 ? (
                          <span className="font-data-mono text-[10px] text-secondary font-semibold flex items-center gap-0.5">
                            <Icon className="text-[13px]">verified</Icon>
                            {evidenceCount} Source{evidenceCount === 1 ? "" : "s"}
                          </span>
                        ) : (
                          <span className="font-data-mono text-[10px] text-on-surface-variant">
                            No sources
                          </span>
                        )}
                      </div>
                      <div>
                        <h2 className="font-headline-sm text-body-lg font-semibold text-on-surface leading-tight">
                          {finding.title}
                        </h2>
                        <p className="font-label-sm text-label-sm text-on-surface-variant">
                          {finding.productName}
                        </p>
                      </div>
                      <div className="flex items-center justify-between pt-1 mt-0.5">
                        <span className="font-data-mono text-[11px] text-on-surface-variant flex items-center gap-1">
                          <Icon className="text-[14px] text-secondary">menu_book</Icon>
                          {finding.id}
                        </span>
                        <Icon className="text-on-surface-variant text-[16px]">chevron_right</Icon>
                      </div>
                    </div>
                  );
                })
              )}
            </div>

            <div className="mt-space-xs p-space-sm bg-surface rounded flex items-center gap-space-sm">
              <Icon className="text-secondary text-[20px]">verified_user</Icon>
              <div className="flex flex-col">
                <span className="font-label-caps text-[10px] uppercase tracking-wider text-on-surface-variant">
                  Retrieval Status
                </span>
                <span className="font-body-sm text-[12px] font-medium text-on-surface">
                  {allEvidence.length} evidence record{allEvidence.length === 1 ? "" : "s"} returned by
                  the backend
                </span>
              </div>
            </div>
          </div>

          {/* CENTER: document canvas */}
          <div className="xl:col-span-5 flex flex-col gap-space-sm bg-surface-container-lowest rounded-xl p-space-sm shadow-sm">
            {selectedEvidence.length === 0 ? (
              <EmptyState
                icon="find_in_page"
                title="No evidence retrieved for this finding"
                description="The RAG system has not returned statutory sources for this finding yet."
              />
            ) : (
              <>
                <div className="flex flex-wrap gap-1 p-1 bg-surface-container-low rounded-lg">
                  {selectedEvidence.map((item, index) => {
                    const isActive = activeEvidence?.id === item.id;
                    return (
                      <button
                        key={item.id}
                        type="button"
                        onClick={() => setActiveEvidenceId(item.id)}
                        className={`flex-1 min-w-[140px] py-1.5 px-2.5 rounded font-label-sm text-label-sm truncate transition-colors flex items-center justify-center gap-1 text-left ${
                          isActive
                            ? "bg-surface-container-lowest text-secondary font-semibold shadow-xs"
                            : "text-on-surface-variant hover:text-on-surface font-medium"
                        }`}
                      >
                        <Icon className="text-[14px] text-secondary">
                          {EVIDENCE_STATUS[item.status].icon}
                        </Icon>
                        <span className="truncate">
                          {index + 1}. {item.authority} ({item.section ?? "section not recorded"})
                        </span>
                      </button>
                    );
                  })}
                </div>

                <div className="flex flex-col gap-1 p-space-sm bg-surface rounded">
                  <div className="flex items-start justify-between gap-space-sm">
                    <div className="flex flex-col">
                      <span className="font-label-caps text-[10px] uppercase tracking-wider text-secondary font-bold">
                        {activeEvidence ? humanize(activeEvidence.sourceTitle) : "Statutory Source"}
                      </span>
                      <h2 className="font-headline-sm text-headline-sm text-on-surface font-semibold leading-tight">
                        {activeEvidence?.documentTitle ?? activeEvidence?.sourceTitle ?? "—"}
                      </h2>
                    </div>
                    {activeEvidence?.sourceUrl ? (
                      <a
                        href={activeEvidence.sourceUrl}
                        target="_blank"
                        rel="noreferrer noopener"
                        title="Open official source"
                        className="text-on-surface-variant hover:text-secondary p-1 rounded"
                      >
                        <Icon className="text-[18px]">open_in_new</Icon>
                      </a>
                    ) : null}
                  </div>
                  <div className="flex flex-wrap items-center gap-x-space-md gap-y-1 mt-1 font-data-mono text-[11px] text-on-surface-variant">
                    <span className="flex items-center gap-1">
                      <Icon className="text-[14px] text-on-surface-variant">account_balance</Icon>
                      {activeEvidence?.authority ?? "—"}
                    </span>
                    {activeEvidence?.version ? (
                      <>
                        <span>•</span>
                        <span>Version: {activeEvidence.version}</span>
                      </>
                    ) : null}
                    {activeEvidence?.effectiveDate ? (
                      <>
                        <span>•</span>
                        <span>Effective: {formatDate(activeEvidence.effectiveDate)}</span>
                      </>
                    ) : null}
                    {activeEvidence?.page ? (
                      <>
                        <span>•</span>
                        <span className="text-secondary font-medium">
                          p.{activeEvidence.page}
                        </span>
                      </>
                    ) : null}
                  </div>
                </div>

                <div className="relative bg-surface-container-lowest rounded p-6 sm:p-8 flex flex-col gap-space-md shadow-inner text-on-surface select-text">
                  <div className="text-center pb-space-sm space-y-1">
                    <div className="flex justify-center items-center gap-2">
                      <Icon className="text-secondary text-[24px]">verified</Icon>
                      <span className="font-label-caps text-[11px] font-bold tracking-[0.2em] text-on-surface uppercase">
                        {activeEvidence?.sourceTitle ?? "Statutory Source"}
                      </span>
                    </div>
                    <p className="font-data-mono text-[10px] text-on-surface-variant uppercase tracking-wider">
                      {activeEvidence?.section ?? "Section not recorded by the backend"}
                      {activeEvidence?.page ? ` • p.${activeEvidence.page}` : ""}
                    </p>
                    <div className="w-24 h-0.5 bg-on-surface-variant/20 mx-auto mt-2" />
                  </div>

                  {activeEvidence?.excerpt ? (
                    <div className="space-y-1">
                      {activeEvidence.section ? (
                        <p className="font-headline-sm text-body-lg font-semibold text-secondary">
                          {activeEvidence.section}
                        </p>
                      ) : null}
                      <p className="font-body-md text-body-md text-on-surface text-justify leading-relaxed whitespace-pre-line">
                        {activeEvidence.excerpt}
                      </p>
                    </div>
                  ) : (
                    <EmptyState
                      compact
                      icon="text_snippet"
                      title="No excerpt returned"
                      description="The backend linked this source but did not return an extracted excerpt."
                    />
                  )}
                </div>
              </>
            )}
          </div>

          {/* RIGHT: analysis detail */}
          <div className="xl:col-span-4 flex flex-col gap-space-sm bg-surface-container-lowest rounded-xl p-space-sm shadow-sm">
            {selected ? (
              <>
                <div className="p-space-sm bg-surface-container rounded-lg flex flex-col gap-space-xs">
                  <div className="flex items-center justify-between">
                    <span className="font-label-caps text-[10px] font-bold text-secondary uppercase tracking-wider">
                      AI Regulatory Finding
                    </span>
                    <span className={`font-data-mono text-[11px] font-semibold flex items-center gap-0.5 ${severityStyle(selected.severity).className.split(" ")[1] ?? "text-on-surface"}`}>
                      <Icon className="text-[14px]">warning</Icon>
                      Severity: {humanize(selected.severity)}
                    </span>
                  </div>
                  <p className="font-body-md text-body-md font-semibold text-on-surface">
                    {selected.title}
                  </p>
                  <div className="mt-1 p-space-sm bg-surface-container-lowest rounded text-on-surface flex flex-col gap-1">
                    <span className="font-label-sm text-[11px] font-semibold text-on-surface flex items-center gap-1">
                      <Icon className="text-[14px] text-secondary">info</Icon>
                      Review metadata
                    </span>
                    <p className="font-body-sm text-body-sm text-on-surface-variant leading-relaxed">
                      Routed from analysis of {selected.productName}. Current review status:{" "}
                      {humanize(selected.status)}.
                    </p>
                  </div>
                </div>

                <div className="p-space-sm bg-surface rounded flex flex-col gap-space-xs">
                  <span className="font-label-caps text-label-caps text-on-surface-variant font-bold uppercase tracking-wider">
                    Statutory Citation
                  </span>
                  {activeEvidence ? (
                    <div className="space-y-1 text-body-sm font-body-sm">
                      <div className="flex justify-between py-0.5">
                        <span className="text-on-surface-variant font-medium">Authority</span>
                        <span className="text-on-surface font-semibold text-right">
                          {activeEvidence.authority}
                        </span>
                      </div>
                      <div className="flex justify-between py-0.5">
                        <span className="text-on-surface-variant font-medium">Source</span>
                        <span className="text-on-surface font-semibold text-right">
                          {activeEvidence.sourceTitle}
                        </span>
                      </div>
                      {activeEvidence.section ? (
                        <div className="flex justify-between py-0.5">
                          <span className="text-on-surface-variant font-medium">Target Clause</span>
                          <span className="font-data-mono text-data-mono text-secondary font-semibold text-right">
                            {activeEvidence.section}
                            {activeEvidence.page ? ` (Page ${activeEvidence.page})` : ""}
                          </span>
                        </div>
                      ) : null}
                    </div>
                  ) : (
                    <p className="text-body-sm text-on-surface-variant">
                      No statutory citation has been returned for this finding.
                    </p>
                  )}
                  {activeEvidence ? (
                    <div className="flex items-center justify-between pt-2">
                      <Badge tone={EVIDENCE_STATUS[activeEvidence.status].tone} icon={EVIDENCE_STATUS[activeEvidence.status].icon}>
                        {humanize(activeEvidence.status)}
                      </Badge>
                      {activeEvidence.sourceUrl ? (
                        <a
                          href={activeEvidence.sourceUrl}
                          target="_blank"
                          rel="noreferrer noopener"
                          className="font-label-sm text-label-sm text-secondary hover:underline flex items-center gap-1 font-semibold"
                        >
                          <span>Open source</span>
                          <Icon className="text-[14px]">open_in_new</Icon>
                        </a>
                      ) : null}
                    </div>
                  ) : null}
                </div>

                <div className="p-space-sm bg-surface rounded flex flex-col gap-space-xs">
                  <span className="font-label-caps text-label-caps text-on-surface-variant font-bold uppercase tracking-wider">
                    Related Records
                  </span>
                  <div className="flex flex-col gap-1.5">
                    <Link
                      href={`/reviews?product=${selected.productId}`}
                      className="h-7 px-2 bg-surface-container-lowest hover:bg-surface-container text-on-surface rounded font-label-sm text-label-sm flex items-center justify-between gap-1 transition-colors"
                    >
                      <span className="flex items-center gap-1">
                        <Icon className="text-[14px] text-secondary">rate_review</Icon>
                        Open in Review Queue
                      </span>
                      <Icon className="text-[14px] text-on-surface-variant">chevron_right</Icon>
                    </Link>
                    <Link
                      href={`/products/${selected.productId}`}
                      className="h-7 px-2 bg-surface-container-lowest hover:bg-surface-container text-on-surface rounded font-label-sm text-label-sm flex items-center justify-between gap-1 transition-colors"
                    >
                      <span className="flex items-center gap-1">
                        <Icon className="text-[14px] text-secondary">inventory_2</Icon>
                        Product dossier
                      </span>
                      <Icon className="text-[14px] text-on-surface-variant">chevron_right</Icon>
                    </Link>
                  </div>
                </div>
              </>
            ) : (
              <EmptyState
                compact
                icon="policy"
                title="No finding selected"
                description="Select a finding to inspect its statutory evidence."
              />
            )}
          </div>
        </div>
      )}
    </div>
  );
}
